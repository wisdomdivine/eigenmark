const BASE_URL = process.env.TEST_BASE_URL || "http://localhost:3000";

let testsRun = 0;
let testsPassed = 0;
let testsFailed = 0;

function logResult(testName, passed, details = "") {
  testsRun++;
  if (passed) {
    testsPassed++;
    console.log(`[PASS] ${testName}`);
  } else {
    testsFailed++;
    console.error(`[FAIL] ${testName} - ${details}`);
  }
}

async function runAllTests() {
  console.log(`\n========================================`);
  console.log(`  EIGENMARK ENDPOINTS E2E TEST SUITE   `);
  console.log(`  Target: ${BASE_URL}                  `);
  console.log(`========================================\n`);

  // --- 1. GET /api/assets ---
  try {
    const res = await fetch(`${BASE_URL}/api/assets`);
    const statusOk = res.status === 200;
    const data = await res.json();
    const isArray = Array.isArray(data);
    logResult("GET /api/assets (Status 200 & Array structure)", statusOk && isArray, `Status: ${res.status}`);

    if (isArray && data.length > 0) {
      const first = data[0];
      const hasFields = first.id && first.contentHash && first.creatorAddress && first.phash;
      logResult("GET /api/assets (Payload schema validation)", Boolean(hasFields), `First item: ${JSON.stringify(first).substring(0, 80)}...`);
    }
  } catch (err) {
    logResult("GET /api/assets", false, err.message);
  }

  // --- 2. POST /api/assets (Validation Error Handling) ---
  try {
    const res = await fetch(`${BASE_URL}/api/assets`, {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({ title: "Incomplete Asset" }),
    });
    logResult("POST /api/assets (400 Bad Request on missing fields)", res.status === 400, `Status: ${res.status}`);
  } catch (err) {
    logResult("POST /api/assets (Validation)", false, err.message);
  }

  // --- 3. POST /api/assets (Successful Insertion) ---
  const testHash = "0x" + Array.from({ length: 64 }, () => Math.floor(Math.random() * 16).toString(16)).join("");
  const testPHash = "0f0f0f0f0f0f0f0f";
  try {
    const res = await fetch(`${BASE_URL}/api/assets`, {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({
        title: "Automated E2E Test Artwork",
        description: "Generated by automated verification runner",
        aiModel: "Stable Diffusion 3.5",
        contentHash: testHash,
        creatorAddress: "0x1111111111111111111111111111111111111111",
        royaltySplit: 25.0,
        phash: testPHash,
        mediaUrl: "https://example.com/test-media.png",
      }),
    });
    const data = await res.json();
    const isSuccess = res.status === 200 && data.contentHash === testHash && Number(data.royaltySplit) === 25;
    logResult("POST /api/assets (200 OK & Database persistence)", isSuccess, `Status: ${res.status}, Body: ${JSON.stringify(data)}`);
  } catch (err) {
    logResult("POST /api/assets (Create)", false, err.message);
  }

  // --- 4. GET /api/agreements ---
  try {
    const res = await fetch(`${BASE_URL}/api/agreements`);
    const statusOk = res.status === 200;
    const data = await res.json();
    logResult("GET /api/agreements (Status 200 & Array structure)", statusOk && Array.isArray(data), `Status: ${res.status}`);
  } catch (err) {
    logResult("GET /api/agreements", false, err.message);
  }

  // --- 5. POST /api/agreements (Validation Error Handling) ---
  try {
    const res = await fetch(`${BASE_URL}/api/agreements`, {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({ price: 10 }),
    });
    logResult("POST /api/agreements (400 Bad Request on missing fields)", res.status === 400, `Status: ${res.status}`);
  } catch (err) {
    logResult("POST /api/agreements (Validation)", false, err.message);
  }

  // --- 6. POST /api/agreements (Successful Insertion) ---
  try {
    const res = await fetch(`${BASE_URL}/api/agreements`, {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({
        assetId: testHash,
        licenseeAddress: "0x2222222222222222222222222222222222222222",
        transactionHash: "0x4f829b10a5620984918e907d471026027ab57849103c80918a20984719082049",
        price: 15.0,
        royaltySplit: 25.0,
      }),
    });
    const data = await res.json();
    const isSuccess = res.status === 200 && data.assetId === testHash && Number(data.price) === 15;
    logResult("POST /api/agreements (200 OK & Database persistence)", isSuccess, `Status: ${res.status}, Body: ${JSON.stringify(data)}`);
  } catch (err) {
    logResult("POST /api/agreements (Create)", false, err.message);
  }

  // --- 7. POST /api/users (User profile registration and resolution) ---
  try {
    const testWallet = "0x981F42cA90b4dE150024823Eb1fA30E6607e47cA";
    const res = await fetch(`${BASE_URL}/api/users`, {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({
        walletAddress: testWallet,
        name: "Autonomous Agent Test Runner",
        role: "Agent Licensee",
      }),
    });
    const data = await res.json();
    const isSuccess = res.status === 200 && data.wallet_address === testWallet;
    logResult("POST /api/users (User profile registration and resolution)", isSuccess, `User: ${data.name} (${data.wallet_address})`);
  } catch (err) {
    logResult("POST /api/users", false, err.message);
  }

  // --- 8. GET /api/mcp (Server Metadata & Tools Catalog) ---
  try {
    const res = await fetch(`${BASE_URL}/api/mcp`);
    const data = await res.json();
    const hasTools = Array.isArray(data.tools) && data.tools.length >= 4;
    const hasMetadata = data.server && data.server.name === "eigenmark-mcp-server";
    logResult("GET /api/mcp (MCP Server Discovery & Tools Catalog)", res.status === 200 && hasTools && hasMetadata, `Tools Count: ${data.tools?.length}`);
  } catch (err) {
    logResult("GET /api/mcp", false, err.message);
  }

  // --- 9. OPTIONS /api/mcp (CORS Preflight) ---
  try {
    const res = await fetch(`${BASE_URL}/api/mcp`, { method: "OPTIONS" });
    const hasCors = res.headers.get("access-control-allow-origin") === "*";
    logResult("OPTIONS /api/mcp (CORS Preflight Headers)", res.status === 204 && hasCors, `Status: ${res.status}`);
  } catch (err) {
    logResult("OPTIONS /api/mcp", false, err.message);
  }

  // --- 10. POST /api/mcp - initialize Handshake ---
  try {
    const res = await fetch(`${BASE_URL}/api/mcp`, {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({
        jsonrpc: "2.0",
        id: 1,
        method: "initialize",
        params: { protocolVersion: "2026-07-28" },
      }),
    });
    const data = await res.json();
    const isSuccess = data.result && data.result.protocolVersion === "2026-07-28";
    logResult("POST /api/mcp (initialize Handshake Protocol)", isSuccess, `Protocol Version: ${data.result?.protocolVersion}`);
  } catch (err) {
    logResult("POST /api/mcp initialize", false, err.message);
  }

  // --- 11. POST /api/mcp - tools/list ---
  try {
    const res = await fetch(`${BASE_URL}/api/mcp`, {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({
        jsonrpc: "2.0",
        id: 2,
        method: "tools/list",
        params: {},
      }),
    });
    const data = await res.json();
    const toolNames = (data.result?.tools || []).map((t) => t.name);
    const hasAllTools = ["verify_provenance", "find_related_assets", "check_usage_policy", "license_asset", "generate_proof_certificate"].every((t) => toolNames.includes(t));
    logResult("POST /api/mcp (tools/list Catalog Verification)", hasAllTools, `Tools: ${toolNames.join(", ")}`);
  } catch (err) {
    logResult("POST /api/mcp tools/list", false, err.message);
  }

  // --- 12. POST /api/mcp - tools/call verify_provenance ---
  try {
    const res = await fetch(`${BASE_URL}/api/mcp`, {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({
        jsonrpc: "2.0",
        id: 3,
        method: "tools/call",
        params: {
          name: "verify_provenance",
          arguments: {
            content_hash: testHash,
          },
        },
      }),
    });
    const data = await res.json();
    const content = JSON.parse(data.result?.content?.[0]?.text || "{}");
    const isVerified = content.status === "verified" && content.registered === true;
    logResult("POST /api/mcp (tools/call verify_provenance)", isVerified, `Result: ${content.status}, Asset ID: ${content.asset?.id}`);
  } catch (err) {
    logResult("POST /api/mcp verify_provenance", false, err.message);
  }

  // --- 13. POST /api/mcp - tools/call find_related_assets ---
  try {
    const res = await fetch(`${BASE_URL}/api/mcp`, {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({
        jsonrpc: "2.0",
        id: 4,
        method: "tools/call",
        params: {
          name: "find_related_assets",
          arguments: {
            phash: testPHash,
            max_distance: 6,
          },
        },
      }),
    });
    const data = await res.json();
    const content = JSON.parse(data.result?.content?.[0]?.text || "{}");
    const isSuccess = Array.isArray(content.matches);
    logResult("POST /api/mcp (tools/call find_related_assets pHash distance)", isSuccess, `Matches found: ${content.matchesFound}`);
  } catch (err) {
    logResult("POST /api/mcp find_related_assets", false, err.message);
  }

  // --- 14. POST /api/mcp - tools/call check_usage_policy ---
  try {
    const res = await fetch(`${BASE_URL}/api/mcp`, {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({
        jsonrpc: "2.0",
        id: 5,
        method: "tools/call",
        params: {
          name: "check_usage_policy",
          arguments: {
            content_hash: testHash,
            intended_use: "commercial_derivative",
          },
        },
      }),
    });
    const data = await res.json();
    const content = JSON.parse(data.result?.content?.[0]?.text || "{}");
    const isAuthorized = content.policyStatus === "AUTHORIZED" && content.licenseFeeUSDC === 10;
    logResult("POST /api/mcp (tools/call check_usage_policy)", isAuthorized, `Policy Status: ${content.policyStatus}, Split: ${JSON.stringify(content.royaltySplitDistribution)}`);
  } catch (err) {
    logResult("POST /api/mcp check_usage_policy", false, err.message);
  }

  // --- 15. POST /api/mcp - tools/call license_asset ---
  try {
    const res = await fetch(`${BASE_URL}/api/mcp`, {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({
        jsonrpc: "2.0",
        id: 6,
        method: "tools/call",
        params: {
          name: "license_asset",
          arguments: {
            content_hash: testHash,
            licensee_address: "0x981F42cA90b4dE150024823Eb1fA30E6607e47cA",
          },
        },
      }),
    });
    const data = await res.json();
    const content = JSON.parse(data.result?.content?.[0]?.text || "{}");
    const isReady = content.status === "READY_FOR_SETTLEMENT" && content.contract === "0x71207757FB3F8118EC0BAb8f2251E09973892306";
    logResult("POST /api/mcp (tools/call license_asset Calldata & Splits)", isReady, `Chain: ${content.chain}, Contract: ${content.contract}`);
  } catch (err) {
    logResult("POST /api/mcp license_asset", false, err.message);
  }

  // --- 16. POST /api/mcp - tools/call generate_proof_certificate ---
  try {
    const res = await fetch(`${BASE_URL}/api/mcp`, {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({
        jsonrpc: "2.0",
        id: 7,
        method: "tools/call",
        params: {
          name: "generate_proof_certificate",
          arguments: {
            transaction_hash: "0x4f829b10a5620984918e907d471026027ab57849103c80918a20984719082049",
            content_hash: testHash,
          },
        },
      }),
    });
    const data = await res.json();
    const content = JSON.parse(data.result?.content?.[0]?.text || "{}");
    const hasCert = content.certificateTokenId && content.ipfsManifestCID;
    logResult("POST /api/mcp (tools/call generate_proof_certificate)", Boolean(hasCert), `Token: ${content.certificateTokenId}, IPFS: ${content.ipfsManifestCID}`);
  } catch (err) {
    logResult("POST /api/mcp generate_proof_certificate", false, err.message);
  }

  // --- 17. POST /api/mcp - Error Handling on Unknown Tool (-32601) ---
  try {
    const res = await fetch(`${BASE_URL}/api/mcp`, {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({
        jsonrpc: "2.0",
        id: 8,
        method: "tools/call",
        params: {
          name: "non_existent_tool_xyz",
          arguments: {},
        },
      }),
    });
    const data = await res.json();
    const isError = data.error && data.error.code === -32601;
    logResult("POST /api/mcp (JSON-RPC 2.0 Error Handling code -32601)", Boolean(isError), `Error: ${data.error?.message}`);
  } catch (err) {
    logResult("POST /api/mcp Error Handling", false, err.message);
  }

  console.log(`\n========================================`);
  console.log(`  E2E TEST RUN COMPLETE                 `);
  console.log(`  Total Tests:  ${testsRun}             `);
  console.log(`  Passed:       ${testsPassed}          `);
  console.log(`  Failed:       ${testsFailed}          `);
  console.log(`========================================\n`);

  if (testsFailed > 0) {
    process.exit(1);
  }
}

runAllTests().catch((err) => {
  console.error("Fatal test runner error:", err);
  process.exit(1);
});
